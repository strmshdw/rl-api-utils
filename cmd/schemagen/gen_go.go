package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

func goEnumTypeName(key string) string {
	switch key {
	case "match_status":
		return "MatchStatus"
	case "replay_stats_status":
		return "ReplayStatsStatus"
	case "player_classification":
		return "PlayerClassification"
	case "sync_mode":
		return "SyncMode"
	case "sse_event_type", "sse_events":
		return "SSEEventType"
	default:
		parts := strings.Split(key, "_")
		for i, p := range parts {
			if p != "" {
				parts[i] = strings.ToUpper(p[:1]) + p[1:]
			}
		}
		return strings.Join(parts, "")
	}
}

func renderGoEnums(schema EnumsSchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/schemagen from schema/enums.yaml; DO NOT EDIT.\n\npackage contracts\n\n")

	keys := make([]string, 0, len(schema.Enums))
	for k := range schema.Enums {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, k := range keys {
		typeName := goEnumTypeName(k)
		buf.WriteString(fmt.Sprintf("// %s represents a canonical enum defined in schema/enums.yaml.\n", typeName))
		buf.WriteString(fmt.Sprintf("type %s string\n\nconst (\n", typeName))
		for _, entry := range schema.Enums[k] {
			buf.WriteString(fmt.Sprintf("\t%s %s = %q\n", entry.Const, typeName, entry.Value))
		}
		buf.WriteString(")\n\n")
	}

	return format.Source(buf.Bytes())
}

func renderGoRanks(schema EnumsSchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/schemagen from schema/enums.yaml; DO NOT EDIT.\n\npackage contracts\n\nimport (\n\t\"fmt\"\n\t\"strings\"\n)\n\n")

	buf.WriteString("var TierNames = [23]string{\n")
	for _, t := range schema.Tiers {
		buf.WriteString(fmt.Sprintf("\t%d: %q,\n", t.ID, t.Name))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var ShortLiveTierNames = [23]string{\n")
	for _, t := range schema.Tiers {
		buf.WriteString(fmt.Sprintf("\t%d: %q,\n", t.ID, t.ShortLive))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var ShortStorageTierNames = [23]string{\n")
	for _, t := range schema.Tiers {
		buf.WriteString(fmt.Sprintf("\t%d: %q,\n", t.ID, t.ShortStorage))
	}
	buf.WriteString("}\n\n")

	writeStringArray := func(name string, vals []string) {
		buf.WriteString(fmt.Sprintf("var %s = [%d]string{", name, len(vals)))
		for i, v := range vals {
			if i > 0 {
				buf.WriteString(", ")
			}
			buf.WriteString(fmt.Sprintf("%q", v))
		}
		buf.WriteString("}\n\n")
	}
	writeStringArray("ZeroBasedDivisionNames", schema.Divisions.ZeroBased)
	writeStringArray("ZeroBasedShortDivisionNames", schema.Divisions.ZeroBasedShort)
	writeStringArray("OneBasedStorageDivisionNames", schema.Divisions.OneBasedStorage)
	writeStringArray("OneBasedShortDivisionNames", schema.Divisions.OneBasedShort)

	buf.WriteString("type PlaylistMetadata struct {\n\tID int\n\tName string\n\tStorageName string\n\tIsRanked bool\n\tIsExtraMode bool\n}\n\n")
	buf.WriteString("var CanonicalPlaylists = map[int]PlaylistMetadata{\n")
	for _, p := range schema.Playlists {
		buf.WriteString(fmt.Sprintf("\t%d: {ID: %d, Name: %q, StorageName: %q, IsRanked: %v, IsExtraMode: %v},\n",
			p.ID, p.ID, p.Name, p.StorageName, p.IsRanked, p.IsExtraMode))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var BallchasingSlugToPlaylist = map[string]int{\n")
	for _, p := range schema.Playlists {
		for _, slug := range p.BallchasingSlugs {
			buf.WriteString(fmt.Sprintf("\t%q: %d,\n", strings.ToLower(slug), p.ID))
		}
	}
	buf.WriteString("}\n\n")

	buf.WriteString(`// FormatPlaylist returns the canonical Rocket League playlist name or "Playlist <id>".
func FormatPlaylist(id int) string {
	if meta, ok := CanonicalPlaylists[id]; ok {
		return meta.Name
	}
	return fmt.Sprintf("Playlist %d", id)
}

// FormatStoragePlaylist returns the legacy storage display name or "Playlist <id>".
func FormatStoragePlaylist(id int) string {
	if meta, ok := CanonicalPlaylists[id]; ok {
		return meta.StorageName
	}
	return fmt.Sprintf("Playlist %d", id)
}

// IsRankedPlaylist reports whether a playlist ID is competitive or tournament.
func IsRankedPlaylist(id int) bool {
	meta, ok := CanonicalPlaylists[id]
	return ok && meta.IsRanked
}

// IsExtraMode reports whether a playlist ID is an Extra Mode.
func IsExtraMode(id int) bool {
	meta, ok := CanonicalPlaylists[id]
	return ok && meta.IsExtraMode
}

// MapPlaylistSlugToID maps a Ballchasing playlist slug to its numeric PsyNet playlist ID.
func MapPlaylistSlugToID(slug string) int {
	if id, ok := BallchasingSlugToPlaylist[strings.ToLower(strings.TrimSpace(slug))]; ok {
		return id
	}
	return 0
}
`)

	return format.Source(buf.Bytes())
}

func renderGoDTOs(schema DTOSchema) ([]byte, error) {
	var buf bytes.Buffer
	needsTime := false
	for _, d := range schema.DTOs {
		for _, f := range d.Fields {
			if strings.Contains(f.GoType, "time.Time") {
				needsTime = true
				break
			}
		}
	}

	buf.WriteString("// Code generated by cmd/schemagen from schema/dto.yaml; DO NOT EDIT.\n\npackage contracts\n\n")
	if needsTime {
		buf.WriteString("import \"time\"\n\n")
	}

	for _, d := range schema.DTOs {
		if d.Doc != "" {
			buf.WriteString(fmt.Sprintf("// %s %s\n", d.Name, d.Doc))
		}
		buf.WriteString(fmt.Sprintf("type %s struct {\n", d.Name))
		for _, f := range d.Fields {
			tag := f.JSON
			if f.Omitempty {
				tag += ",omitempty"
			}
			buf.WriteString(fmt.Sprintf("\t%s %s `json:%q`\n", f.Name, f.GoType, tag))
		}
		buf.WriteString("}\n\n")
	}

	return format.Source(buf.Bytes())
}
