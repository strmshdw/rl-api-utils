package main

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

func renderTSEnums(schema EnumsSchema) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/schemagen from schema/enums.yaml; DO NOT EDIT.\n\n")

	keys := make([]string, 0, len(schema.Enums))
	for k := range schema.Enums {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, k := range keys {
		typeName := goEnumTypeName(k)
		values := make([]string, 0, len(schema.Enums[k]))
		for _, entry := range schema.Enums[k] {
			values = append(values, fmt.Sprintf("%q", entry.Value))
		}
		buf.WriteString(fmt.Sprintf("export type %s = %s;\n", typeName, strings.Join(values, " | ")))

		constMapName := strings.ToUpper(k)
		buf.WriteString(fmt.Sprintf("export const %s = {\n", constMapName))
		for _, entry := range schema.Enums[k] {
			buf.WriteString(fmt.Sprintf("  %s: %q as %s,\n", entry.TSConst, entry.Value, typeName))
		}
		buf.WriteString("} as const;\n\n")
	}

	buf.WriteString("export interface PlaylistMeta {\n  id: number;\n  name: string;\n  storageName: string;\n  isRanked: boolean;\n  isExtraMode: boolean;\n}\n\n")
	buf.WriteString("export const PLAYLIST_CATALOG: Record<number, PlaylistMeta> = {\n")
	for _, p := range schema.Playlists {
		buf.WriteString(fmt.Sprintf("  %d: { id: %d, name: %q, storageName: %q, isRanked: %v, isExtraMode: %v },\n",
			p.ID, p.ID, p.Name, p.StorageName, p.IsRanked, p.IsExtraMode))
	}
	buf.WriteString("};\n")

	return buf.Bytes()
}

func renderTSColumns(schema TelemetrySchema) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/schemagen from schema/telemetry.yaml; DO NOT EDIT.\n\n")

	colKeys := make([]string, len(schema.ColumnOrder))
	for i, k := range schema.ColumnOrder {
		colKeys[i] = fmt.Sprintf("%q", k)
	}
	buf.WriteString(fmt.Sprintf("export type StatColumnKey =\n  | %s;\n\n", strings.Join(colKeys, "\n  | ")))
	buf.WriteString("export type ColumnConfig = Record<StatColumnKey, boolean>;\n\n")
	buf.WriteString("export type PresetKey = 'full' | 'competitive' | 'streamer';\n\n")
	buf.WriteString("export interface ColumnDefinition {\n  key: StatColumnKey;\n  label: string;\n  shortLabel: string;\n  description: string;\n}\n\n")

	colByKey := make(map[string]StatColumnDef, len(schema.StatColumns))
	for _, c := range schema.StatColumns {
		colByKey[c.Key] = c
	}

	buf.WriteString("export const STAT_COLUMNS: ColumnDefinition[] = [\n")
	for _, key := range schema.ColumnOrder {
		c := colByKey[key]
		buf.WriteString(fmt.Sprintf("  { key: %q, label: %q, shortLabel: %q, description: %q },\n",
			c.Key, c.Label, c.ShortLabel, c.Description))
	}
	buf.WriteString("];\n\n")

	presetOrder := []string{"full", "competitive", "streamer"}
	buf.WriteString("export const PRESETS: Record<PresetKey, { name: string; description: string; columns: StatColumnKey[] }> = {\n")
	for _, k := range presetOrder {
		p := schema.Presets[k]
		quoted := make([]string, len(p.Columns))
		for i, col := range p.Columns {
			quoted[i] = fmt.Sprintf("%q", col)
		}
		buf.WriteString(fmt.Sprintf("  %s: {\n    name: %q,\n    description: %q,\n    columns: [%s],\n  },\n",
			k, p.Name, p.Description, strings.Join(quoted, ", ")))
	}
	buf.WriteString("};\n")

	return buf.Bytes()
}

func renderTSDTOs(schema DTOSchema) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/schemagen from schema/dto.yaml; DO NOT EDIT.\n\n")

	for _, d := range schema.DTOs {
		name := d.TSName
		if name == "" {
			name = d.Name
		}
		if d.Doc != "" {
			buf.WriteString(fmt.Sprintf("/** %s */\n", d.Doc))
		}
		buf.WriteString(fmt.Sprintf("export interface %s {\n", name))
		for _, f := range d.Fields {
			opt := ""
			tsType := f.TSType
			if strings.HasSuffix(tsType, "?") {
				opt = "?"
				tsType = strings.TrimSuffix(tsType, "?")
			} else if f.Omitempty {
				opt = "?"
			}
			buf.WriteString(fmt.Sprintf("  %s%s: %s;\n", f.JSON, opt, tsType))
		}
		buf.WriteString("}\n\n")
	}

	return buf.Bytes()
}
